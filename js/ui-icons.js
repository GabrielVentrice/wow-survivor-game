/* =========================================================================
   O ACERVO DE ICONE — um desenho por peca, em osso monocromatico.

   As dez primitivas geometricas eram o FALLBACK, e por um tempo elas viraram
   o acervo inteiro. O resultado, medido na tira do HUD: nove peças, quatro
   marcas distintas — dois `|`, dois `●`, dois `=` — e duas peças diferentes
   caindo na mesma forma. O emoji era pior esteticamente e MELHOR em
   reconhecimento, e trocar reconhecimento por estetica num elemento cuja
   unica funcao e ser reconhecido e uma troca ruim.

   Entao: grade propria para cada peca, e primitiva so para o que ainda nao
   tem. Onde o mundo ja desenhou a coisa — os demonios — o icone continua
   sendo a grade DELE (ver GLIFO_SPRITE em js/ui-glyph.js): e o unico caso em
   que o icone pode ser a coisa em vez de um simbolo dela.

   REGRAS DA GRADE

   - 16x16, `#` cheio e `.` vazio. Mono: nao ha rampa, nao ha segundo tom. O
     que informa e a SILHUETA, e o que a torna legivel a 30px e o vazio dentro
     dela — buraco de olho, vao de costela, miolo de anel. Desenho sem furo
     vira mancha.
   - Uma peca, uma ideia. A 16px nao cabe cena: cabe um objeto.
   - FAMILIA importa tanto quanto distincao. As de fogo compartilham a chama,
     as de podridao compartilham o cranio, as de defesa compartilham o escudo.
     Na tira o jogador le o eixo pela cor, a familia pela silhueta e a peca
     pelo detalhe — nessa ordem, e nesse tempo.
   - Traco de 2 celulas onde puder. Traco de 1 celula some quando o icone e
     desenhado a 24px na linha compacta da pausa.
   ========================================================================= */

