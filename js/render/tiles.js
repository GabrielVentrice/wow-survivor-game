/* =========================================================================
   TILES — as oito lajes do chão, desenhadas à mão a partir de referência.

   O chão era gerado por código (`makeFelTile` sorteava granulado, juntas e
   veios). Isto aqui é o mesmo chão como DADO: uma grade de 42x42 por laje,
   nos tokens da PAL, do mesmo tamanho em que ela aparece — `BALANCE.world.tile`
   (126) dividido por `PIXEL_UNIT` (3). Nada é reescalado no blit.

   Three rules paid for in the conversion, and each is visible the moment it is
   broken:

   1. A tile is seen forty times on one screen, so it may carry STRUCTURE and
      never a BLOTCH. Each slab was high-passed before being quantised: what
      survives is the joint, the crack and the grain, and what dies is how light
      the reference happened to paint that face. A lighter face kept its value
      and came back as a lit pad stamped across the floor.
   2. A slab carrying a mark — a fel vein, a rune — is singular, so it is RARE.
      `TILE_BAG` weights the plain ones five to one; picking uniformly put a
      rune on one cell in eight and the eye found the lattice immediately.
   3. Eight stamps still repeat. Mirroring is free (integer flip, no resampling,
      so the pixel grid is untouched) and turns eight slabs into thirty-two.

   O vocabulário de char é o mesmo dos sprites: `o` contorno, `d`/`m`/`l` a
   rampa, `e`/`E` energia. A laje é matéria — o verde e a runa juntos ficam em
   0,8% dos pixels, bem abaixo do teto de 14% da regra de corpo aceso.
   ========================================================================= */

