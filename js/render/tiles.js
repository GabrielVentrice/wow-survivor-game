/* Índices das lajes que carregam marca (veio ou runa). Sai do dado, não de uma
   lista à mão: laje nova com veio entra em raro sozinha. */
const TILE_MARKED = TILE_ROWS.map((rows, i) =>
  rows.some((r) => r.includes("e") || r.includes("E") || r.includes("f")) ? i : -1
).filter((i) => i >= 0);

const TILE_BAG = (() => {
  const bag = [];
  for (let i = 0; i < TILE_ROWS.length; i++) {
    if (TILE_MARKED.indexOf(i) >= 0) bag.push(i);
    else for (let k = 0; k < 5; k++) bag.push(i);
  }
  return bag;
})();
